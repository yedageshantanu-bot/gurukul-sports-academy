async function main() {
  const voiceId = 'JBFqnCBsd6RMkjVDRZzb'; // George - Warm, Expressive, Multilingual
  console.log(`Calling ElevenLabs API (Voice ID: ${voiceId}, Model: eleven_multilingual_v2)...`);

  const response = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${voiceId}`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'xi-api-key': apiKey,
    },
    body: JSON.stringify({
      text: scriptText,
      model_id: 'eleven_multilingual_v2',
      voice_settings: {
        stability: 0.5,
        similarity_boost: 0.85,
        style: 0.15,
        use_speaker_boost: true,
      },
    }),
  });

  if (!response.ok) {
    const err = await response.text();
    console.error('ElevenLabs API Error:', response.status, err);
    process.exit(1);
  }

  const arrayBuffer = await response.arrayBuffer();
  const buffer = Buffer.from(arrayBuffer);
  const outputPath = path.join(__dirname, 'elevenlabs_gurukul_hindi_report.mp3');
  fs.writeFileSync(outputPath, buffer);
  console.log(`ElevenLabs Hindi Audio Report successfully generated: ${outputPath} (${buffer.length} bytes)`);
}

main().catch(console.error);
